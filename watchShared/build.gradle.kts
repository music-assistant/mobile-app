import java.util.Properties

plugins {
    alias(libs.plugins.kotlinMultiplatform)
    alias(libs.plugins.kotlinSerialization)
}

/**
 * Server coordinates and the long-lived token, read from the git-ignored `local.properties`
 * at the repository root — the same placeholder sign-in the Wear OS module uses, for the same
 * reason: the token never reaches a commit, and swapping servers is a rebuild rather than an
 * edit. Replacing it with a real sign-in means changing how [WatchServerConfig] is built and
 * nothing else.
 *
 * ```
 * ma.host=192.168.1.10
 * ma.port=8095
 * ma.tls=false
 * ma.token=<long-lived access token>
 * ```
 */
val localProperties = Properties().apply {
    rootProject.file("local.properties").takeIf { it.exists() }?.inputStream()?.use(::load)
}

fun localProperty(key: String, fallback: String): String =
    (localProperties[key] as? String)?.trim()?.takeIf { it.isNotEmpty() } ?: fallback

val configuredHost = localProperty("ma.host", "homeassistant.local")
val configuredPort = localProperty("ma.port", "8095")
val configuredTls = localProperty("ma.tls", "false")
val configuredToken = localProperty("ma.token", "")

/**
 * Kotlin Multiplatform has no `BuildConfig`, so the four values are generated as one object
 * into a source dir of `commonMain`. Registering the task itself as the source dir is what
 * carries the build dependency, so a changed `local.properties` regenerates before compiling.
 */
val generateWatchBuildConfig = tasks.register("generateWatchBuildConfig") {
    description = "Writes the server coordinates from local.properties into a Kotlin source file."
    val outputDir = layout.buildDirectory.dir("generated/watchBuildConfig/kotlin")
    val host = configuredHost
    val port = configuredPort
    val tls = configuredTls
    val token = configuredToken
    inputs.property("host", host)
    inputs.property("port", port)
    inputs.property("tls", tls)
    inputs.property("token", token)
    outputs.dir(outputDir)
    doLast {
        val target = outputDir.get().asFile
            .resolve("io/music_assistant/client/watch/data/WatchBuildConfig.kt")
        target.parentFile.mkdirs()
        target.writeText(
            """
            // Generated by :watchShared:generateWatchBuildConfig. Do not edit.
            package io.music_assistant.client.watch.data

            internal object WatchBuildConfig {
                const val HOST: String = "${host.kotlinEscaped()}"
                const val PORT: Int = ${port.toIntOrNull() ?: 8095}
                const val TLS: Boolean = ${tls.toBoolean()}
                const val TOKEN: String = "${token.kotlinEscaped()}"
            }

            """.trimIndent(),
        )
    }
}

fun String.kotlinEscaped(): String = replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")

kotlin {
    // Three device/simulator slices, because Xcode builds a watchOS app for `arm64_32`
    // (every Apple Watch since Series 4) and `arm64` (the S9 generation and newer), and
    // runs it on an `arm64` simulator.
    listOf(
        watchosArm64(),
        watchosDeviceArm64(),
        watchosSimulatorArm64(),
    ).forEach { watchTarget ->
        watchTarget.binaries.framework {
            baseName = "MaWatchKit"
            // Static: the watch app is the only consumer, and a static framework needs no
            // embedding step and no dyld work at launch.
            isStatic = true
            binaryOption("bundleId", "io.music_assistant.client.watchkit")
        }
    }

    sourceSets {
        commonMain {
            kotlin.srcDir(generateWatchBuildConfig)
            dependencies {
                implementation(libs.ktor.client.core)
                implementation(libs.ktor.client.websockets)
                // Not used as a WebSocket content converter — the session frames its own
                // JSON. It is here because it brings kotlinx-serialization-json as an api
                // dependency, which is how every other module in this build gets it.
                implementation(libs.ktor.client.json)
                implementation(libs.kotlinx.coroutines.core)
                implementation(libs.kermit)
            }
        }

        commonTest.dependencies {
            implementation(libs.kotlin.test)
            implementation(libs.kotlinx.coroutines.test)
        }

        watchosMain.dependencies {
            implementation(libs.ktor.client.darwin)
        }
    }
}
